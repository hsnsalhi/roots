import { useEffect } from 'react';
import { arNum } from '../roots';
import type { IndexFile } from '../types';

export default function About({ index, onClose }: { index: IndexFile | null; onClose: () => void }) {
  useEffect(() => {
    const onKey = (e: KeyboardEvent) => e.key === 'Escape' && onClose();
    document.addEventListener('keydown', onKey);
    return () => document.removeEventListener('keydown', onKey);
  }, [onClose]);
  const c = index?.meta.counts;
  return (
    <div className="modal-bg" onClick={onClose}>
      <div className="modal" role="dialog" aria-modal="true" aria-labelledby="about-title" onClick={(e) => e.stopPropagation()}>
        <button className="iconbtn close" aria-label="إغلاق" onClick={onClose}>
          <svg viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2" aria-hidden="true"><path d="M6 6l12 12M18 6 6 18" /></svg>
        </button>
        <h2 id="about-title">غابة الجذور</h2>
        <p>
          خريطة تفاعلية لجذور أفعال القرآن الكريم. كلّ شجرة في الغابة تمثّل <b>جذرًا ثنائيًا</b>، وتتفرّع منها الجذور
          الثلاثية التي تشترك في هذين الحرفين، ثم الأفعال الواردة في القرآن من كلّ جذر، مع تصريفاتها ومواضعها في المصحف،
          ومعاني الجذر في معجمين من أمّهات المعاجم.
        </p>

        <h3>فكرة الجذر الثنائي</h3>
        <p>
          ذهب عدد من علماء العربية قديمًا وحديثًا إلى أنّ الجذور الثلاثية ترجع في أصلها إلى نواة ثنائية تحمل المعنى العامّ،
          ثم يخصّص الحرف الثالث ذلك المعنى. ومن أشهر ما يُستأنس به في ذلك ما سمّاه ابن جنّي في «الخصائص» <b>الاشتقاق الأكبر</b>،
          وما بناه ابن فارس في «مقاييس اللغة» من ردّ كلّ جذر إلى أصل أو أصول معنوية، ثم دراسات المحدثين في الثنائية.
          هذا التطبيق أداة للاستقراء والمقارنة: ضع الجذور التي تتشارك في حرفين متجاورين جنبًا إلى جنب، واقرأ أصولها
          عند ابن فارس، وتأمّل الخيط الجامع بينها.
        </p>
        <p>
          ولأنّ العلماء اختلفوا في كيفية استخراج النواة الثنائية، يتيح التطبيق قاعدتين (من الإعدادات): <b>الحرفان الأولان</b>
          من الجذر، أو <b>الحرفان الصحيحان</b> بعد إسقاط حرف العلّة والتضعيف.
        </p>

        <h3>كيف تقرأ الغابة؟</h3>
        <ul>
          <li>الغابة مشهد ثلاثي الأبعاد: اسحب بالفأرة للدوران، وكبّر بالعجلة أو بإصبعين، وحرّك بالزر الأيمن أو بإصبعين معًا. الأشجار مجموعة في بساتين بحسب الحرف الأول، ولكلّ بستان لافتة خشبية بحرفه؛ استعمل شريط الحروف أو الخريطة المصغّرة أو البحث للانتقال.</li>
          <li>ارتفاع الشجرة يدلّ على عدد مواضع أفعالها في القرآن، وفوق كلّ شجرة لوحة بحرفي جذرها. الشجيرات الصغيرة جذورٌ لم يرد منها فعل، والأشجار البرّية حول البساتين زينة لا غير.</li>
          <li>انقر على شجرة لتراها عن قرب: كلّ غصن جذر ثلاثي، وكلّ فرع منه فعل. الفروع الخضراء المورقة أفعال وردت في القرآن، والفروع الرمادية الجرداء أفعال من الجذر وردت في المعاجم ولم ترد في القرآن (يمكن إخفاؤها من الإعدادات). انقر على الغصن لقراءة معناه في المعاجم ومشتقّاته الاسمية، وعلى الفعل لعرض تصريفاته وآياته أو مصادره.</li>
          <li>اللوحة الصغيرة عند جذع الشجرة تحمل <b>المعنى الجامع</b> للمجموعة: خلاصة استقرائية استُخلصت من الأصول التي يذكرها ابن فارس لجذور المجموعة، ولا تُعرض إلا حين يجمع أكثر الجذور خيطٌ واحد. وهي اجتهاد قابل للمراجعة، لا نصّ معجمي.</li>
        </ul>

        <h3>المصادر</h3>
        <ul>
          <li>
            <b>التحليل الصرفي والجذور:</b> مدوّنة القرآن العربية (Quranic Arabic Corpus)، الإصدار 0.4، جامعة ليدز، بإشراف كايس دوكس
            — رخصة GNU GPL؛ عبر النسخة العربية الحروف المعدّلة في مشروع <code>quran-morphology</code>.
          </li>
          <li>
            <b>نصّ المصحف:</b> مشروع تنزيل (tanzil.net)، الرسم العثماني، الإصدار 1.1 — رخصة CC BY 3.0، النصّ منقول حرفيًا من غير تغيير.
          </li>
          <li>
            <b>معاني الجذور:</b> ابن فارس، ت 1004 م (395 هـ)، «معجم مقاييس اللغة»؛ والراغب الأصفهاني، ت 1108 م (502 هـ)، «المفردات في غريب القرآن»؛
            والجوهري، ت 1003 م (393 هـ)، «الصحاح»؛ والفيروزآبادي، ت 1415 م (817 هـ)، «القاموس المحيط»؛ وابن منظور، ت 1311 م (711 هـ)، «لسان العرب»
            — نصوص تراثية في الملك العام، عبر مدوّنة OpenITI (رقمنة المكتبة الشاملة). حُذفت مقدّمات المحقّقين وحواشيهم، وقد تبقى في النصّ آثار من الرقمنة الآلية.
          </li>
          <li>
            <b>أفعال الجذر خارج القرآن:</b> معجم الرموز الوسيط (طه زروقي ومحمد كبداني، رخصة GNU GPL)، وويكاموس الإنجليزي
            (Wiktionary، رخصة CC BY-SA 4.0، عبر مستخرج kaikki.org)، ثم مواد الجذور في الصحاح والقاموس المحيط ولسان العرب.
            يُذكر عند كلّ فعل المصادر التي وُجد فيها؛ والتوثيق من المعاجم القديمة آليّ يعتمد على صيغ الاستشهاد المعتادة (فَعَلَ يَفْعُلُ،
            المصادر، أوزان المزيد) في مادّة الجذر، فقد يفوته فعل أو يخطئ في آخر.
          </li>
        </ul>
        {c && (
          <p className="note">
            الأرقام: {arNum(c.roots)} جذرًا، منها {arNum(c.verbRoots)} جذرًا ورد منه فعل؛ {arNum(c.verbLemmas)} فعلًا في {arNum(c.verbTokens)} موضعًا؛
            و{arNum(c.nounLemmas)} مشتقًّا اسميًا. مداخل ابن فارس: {arNum(c.maqayis)}، مداخل الراغب: {arNum(c.mufradat)}،
            الصحاح: {arNum(c.sihah)}، القاموس: {arNum(c.qamus)}، اللسان: {arNum(c.lisan)}. أفعال المعاجم: {arNum(c.lexVerbs)} فعلًا،
            منها {arNum(c.lexOther)} لم ترد في القرآن.
          </p>
        )}

        <h3>تنبيهات</h3>
        <ul>
          <li>تُعرض أوزان الأفعال وصيغها كما وردت في المدوّنة؛ وحين تذكر المدوّنة الفعل بصيغة مضارع أو صيغة مصرّفة (لأنّ ماضيه لم يرد في القرآن) رُدّ إلى صيغة الماضي المعجمية بالمطابقة مع المعاجم.</li>
          <li>إسناد الجذور إلى نواة ثنائية اجتهاد يُقصد به الاستقراء والمقارنة لا الجزم، والحكم في ذلك لأهل اللغة.</li>
          <li>الشيفرة المصدرية مفتوحة على GitHub، والبيانات تُبنى آليًا من المصادر أعلاه بواسطة <code>scripts/build_data.py</code>.</li>
        </ul>
      </div>
    </div>
  );
}
